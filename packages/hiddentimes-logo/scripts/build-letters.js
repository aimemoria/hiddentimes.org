// Paints the HiddenTimes letters and the badge symbol with the brush (src/letters-design.js) and
// writes the finished shapes to src/brush-paths.js, so browsers get ready-made shapes and the logo
// appears instantly. Run by  npm run build  before the SVG files are made.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { WORDMARK, WORDMARK_TOP, WORDMARK_CAP, WORDMARK_EM, symbolBrush, ensoBrush, SMALL_STYLE, paint, rng } from '../src/letters-design.js';
import { BASE_SYMBOL, BASE_CIRCLE, italicPoint } from '../src/symbol-path.js';

const ringR = Math.min(BASE_CIRCLE.rx, BASE_CIRCLE.ry) - 26;
const ring = ensoBrush(BASE_CIRCLE.cx, BASE_CIRCLE.cy, ringR, { lean: italicPoint });
const ringSmall = ensoBrush(BASE_CIRCLE.cx, BASE_CIRCLE.cy, ringR, { lean: italicPoint, style: { ...SMALL_STYLE, width: 66 } });

const out = fileURLToPath(new URL('../src/brush-paths.js', import.meta.url));
writeFileSync(out, `// Generated by scripts/build-letters.js from src/letters-design.js. Do not edit by hand:
// change letters-design.js and run  npm run build.

export const WORDMARK = ${JSON.stringify(WORDMARK)};

export const WORDMARK_TOP = ${WORDMARK_TOP};
export const WORDMARK_CAP = ${WORDMARK_CAP};
export const WORDMARK_EM = ${WORDMARK_EM};

// The badge symbol painted with the brush, before the layout moves the badge (shapes.js shifts it).
export const SYMBOL_BRUSH_BASE = ${JSON.stringify(symbolBrush(BASE_SYMBOL.d))};

// The badge: an open brush ring around the symbol, and the guide line its animation follows.
export const RING_BRUSH_BASE = ${JSON.stringify(ring.d)};
export const RING_GUIDE_BASE = ${JSON.stringify(ring.guide)};

// The same badge for tiny sizes (browser-tab icon): solid brush, no dry streaks.
export const SMALL_RING_BASE = ${JSON.stringify(ringSmall.d)};
export const SMALL_SYMBOL_BASE = ${JSON.stringify(symbolBrush(BASE_SYMBOL.d, { ...SMALL_STYLE, width: 52 }))};
`);
console.log('src/brush-paths.js');

// A short brush stroke for the website itself (the underline of the active menu item, the dash on
// text-only story cards), painted with the same brush so the pages match the logo. The site colours
// it with CSS (it is used as a mask), so it stays the brand yellow.
{
  const polys = paint([[40, 110], [600, 90], [1200, 115], [1960, 95]], { width: 120, minRatio: 0.9, bristles: 3, tail: 0.3, taper: 0.15, rough: 7, angle: 90 }, rng(21));
  const d = polys.map((p) => 'M' + p.map(([x, y]) => `${Math.round(x)} ${Math.round(y)}`).join('L') + 'Z').join('');
  const file = fileURLToPath(new URL('../dist/brush-underline.svg', import.meta.url));
  writeFileSync(file, `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 2000 200" preserveAspectRatio="none"><path d="${d}"/></svg>
`);
  console.log('dist/brush-underline.svg');
}
